import dj_database_url

DATABASE_URL = os.environ.get('DATABASE_URL')
SQLITE_DB_PATH = os.environ.get('SQLITE_DB_PATH')
USE_SQLITE = os.environ.get('USE_SQLITE', 'false').lower() in {'1', 'true', 'yes', 'on'}
IS_RENDER = os.environ.get('RENDER', '').lower() in {'1', 'true', 'yes', 'on'}
LEGACY_RENDER_DATABASE_NAME = False

if DATABASE_URL and not USE_SQLITE:
    if '://' not in DATABASE_URL:
        # Existing Render services can retain a legacy database-name value such
        # as "dhangongo". It is not a usable connection string, so it must not
        # prevent collectstatic or migrations from starting.
        if IS_RENDER:
            USE_SQLITE = True
            LEGACY_RENDER_DATABASE_NAME = True
        else:
            raise ImproperlyConfigured(
                'DATABASE_URL is invalid. It must be a full connection string like postgres://user:pass@host:port/dbname, not just a service name.'
            )

    if not USE_SQLITE:
        DATABASES = {
            'default': dj_database_url.parse(DATABASE_URL, conn_max_age=600, ssl_require=False)
        }

if SQLITE_DB_PATH or USE_SQLITE:
    # Prefer the explicitly-configured SQLITE_DB_PATH (used at runtime on Render).
    # If the configured parent directory can be created and is writable, use it.
    # In debug mode, fallback to BASE_DIR/db.sqlite3 if necessary. In production,
    # do not silently switch to an ephemeral local database.
    candidate = str(BASE_DIR / 'db.sqlite3') if LEGACY_RENDER_DATABASE_NAME else (SQLITE_DB_PATH or str(BASE_DIR / 'db.sqlite3'))
    parent = os.path.dirname(candidate)
    use_candidate = False
    if parent in ('', '/'):
        use_candidate = True
    else:
        _ensure_parent_directory(candidate)
        if os.path.isdir(parent) and os.access(parent, os.W_OK):
            if not IS_RENDER or not candidate.startswith('/data') or os.path.ismount(parent):
                use_candidate = True

    if use_candidate:
        sqlite_path = candidate
    elif DEBUG:
        sqlite_path = str(BASE_DIR / 'db.sqlite3')
    else:
        raise ImproperlyConfigured(
            f"The configured sqlite path '{candidate}' is not writable or is not mounted. "
            "Production must use a persistent sqlite mount or a valid DATABASE_URL."
        )

    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.sqlite3',
            'NAME': sqlite_path,
        }
    }
else:
    if DEBUG:
        sqlite_path = str(BASE_DIR / 'db.sqlite3')
        DATABASES = {
            'default': {
                'ENGINE': 'django.db.backends.sqlite3',
                'NAME': sqlite_path,
            }
        }
    else:
        raise ImproperlyConfigured('DATABASE_URL is not set. Production must use the Render database.')


